/**
 * runner.js — Entry point child process (fork).
 *
 * Dijalankan oleh parent (server/routes/run.js) lewat `child_process.fork`.
 * Menerima pesan `{ type: "start", payload }`, menjalankan script, mengirim
 * event via `process.send({ type: "event", event })`, dan keluar.
 *
 * Plan §7.3: hasil run disimpan ke cache oleh parent; runner hanya kirim event.
 */

import { pathToFileURL } from "node:url";

import { HttpClient } from "./http-client.js";
import * as vuserApi from "./vuser-api.js";

// Bind vuser-api ke runner context
const vu = {
  http: null,
  params: new Map(),
  transaction: { name: null, startMs: 0 },
  currentFile: "",
  currentLine: 0,
  currentIteration: 1,  // Track current iteration
  runOptions: {},
  seq: 0,            // counter step, runner yang memberi nomor
  runStartMs: 0,     // epoch ms awal run (untuk timing.startMs)
  cacheDir: "",
  runId: "",
  log: (level, msg) => {
    sendEvent("log", { level, msg, file: vu.currentFile, line: vu.currentLine, iteration: vu.currentIteration });
  },
  sendEvent,
  __at: (file, line) => {
    vu.currentFile = file;
    vu.currentLine = line;
  },
  __unsupported: (raw, file, line) => {
    vu.log("warn", `Unsupported: ${raw} at ${file}:${line}`);
    return Promise.resolve(0);
  },
  __unsupportedCall: (name, file, line) => {
    vu.log("warn", `Unsupported call: ${name} at ${file}:${line}`);
    return Promise.resolve(0);
  },
};

// Attach all vuser-api functions to vu object
Object.assign(vu, vuserApi);

vuserApi.__bind(vu);

/** Kirim event ke parent process */
function sendEvent(type, data, callback) {
  process.send({ type: "event", event: { type, data, ts: Date.now() } }, callback);
}

/** Main run logic */
async function run(payload) {

  try {
    const { modulePath, options, runId, cacheDir, parameterFiles } = payload;

    vu.runId = runId;
    vu.cacheDir = cacheDir;
    vu.seq = 0;
    vu.runStartMs = Date.now();

    vu.runOptions = {
      thinkTime: options.thinkTime || "ignore",
      insecureTLS: options.insecureTLS || false,
      timeoutMs: options.timeoutMs || 60000,
      continueOnError: options.continueOnError || false,
      iterationDelayMs: options.iterationDelayMs || 0,
      newUserEachIteration: options.newUserEachIteration !== false,
    };

    // Initialize parameter files for sequential substitution
    // parameterFiles is a Map serialized as array of [key, { values, currentIndex }]
    const paramFileMap = new Map();
    if (parameterFiles) {
      for (const [key, value] of parameterFiles) {
        paramFileMap.set(key, { values: value.values, currentIndex: 0 });
      }
    }
    vu.parameterFiles = paramFileMap;

    // Initialize params with first values from parameter files (for lr_eval_string substitution)
    for (const [key, value] of vu.parameterFiles) {
      if (value.values.length > 0) {
        vu.params.set(key, value.values[0]);
      }
    }

    // Initialize HTTP client
    vu.http = new HttpClient({
      timeoutMs: vu.runOptions.timeoutMs,
      insecureTLS: vu.runOptions.insecureTLS,
      followRedirects: true,
      maxRedirects: 10,
      debugCallback: (level, msg) => sendEvent("log", { level, msg }),
    });

    // Import transpiled module
    const moduleUrl = `${pathToFileURL(modulePath).href}?t=${Date.now()}`;
    let mod;
    try {
      mod = await import(moduleUrl);
    } catch (error) {
      sendEvent("error", { message: `Failed to load transpiled module: ${error.message}` });
      process.exit(1);
    }

    // Bind vuser-api to module
    mod.__bind(vu);

    // Use __entries from module (generated by transpiler)
    // __entries maps action names to FUNCTIONS directly
    const entries = mod.__entries || {};
    // __entries berkunci basename file .c ("Action", "vuser_init"); Run Logic dari loader
    // berisi nama file ("vuser_init.c") atau { name, file } — cocokkan lewat basename file.
    const entryKey = (ref) => {
      const raw = typeof ref === "string" ? ref : (ref?.file || ref?.name || "");
      return raw.split(/[\\/]/).pop().replace(/\.[^.]+$/, "");
    };
    const resolveFn = (ref) => {
      const key = entryKey(ref);
      const found = Object.keys(entries).find((name) => name === key) ?? Object.keys(entries).find((name) => name.toLowerCase() === key.toLowerCase());
      return found && typeof entries[found] === "function" ? { name: found, fn: entries[found] } : null;
    };

    // Run order dari Run Logic: vuser_init -> action utama (hanya yang pertama diiterasi) -> vuser_end
    const runLogic = payload.runLogic || { init: "vuser_init", actions: ["Action"], end: "vuser_end" };
    const actions = [];
    const initFn = runLogic.init && resolveFn(runLogic.init);
    if (initFn) actions.push({ ...initFn, iterations: 1 });
    const mainFn = resolveFn(runLogic.actions?.[0] || "Action");
    if (mainFn) actions.push({ ...mainFn, iterations: options.iterations || 1 });
    const endFn = runLogic.end && resolveFn(runLogic.end);
    if (endFn) actions.push({ ...endFn, iterations: 1 });

    sendEvent("started", { runId, actions: actions.map(a => a.name) });

    let globalError = null;

    for (const action of actions) {
      for (let iter = 1; iter <= action.iterations; iter++) {
        if (globalError && !vu.runOptions.continueOnError) break;

        // New user each iteration: clear cookies, reset params (except saved ones)
        if (vu.runOptions.newUserEachIteration && iter > 1) {
          vu.http.clearCookies();
          vuserApi.__resetHeaders();
          // Note: lr_save_string params persist across iterations per plan §6
          // Only correlation params are overwritten each iteration
        }

        // Advance parameter files for this iteration (sequential mode)
        // Each iteration gets the next row from each parameter file
        if (iter > 1 && vu.parameterFiles) {
          for (const [paramName, paramFile] of vu.parameterFiles) {
            if (paramFile.currentIndex < paramFile.values.length - 1) {
              paramFile.currentIndex++;
            } else {
              // Wrap around to beginning (VuGen behavior)
              paramFile.currentIndex = 0;
            }
            // Substitute into runtime params
            vu.params.set(paramName, paramFile.values[paramFile.currentIndex]);
          }
        }

        sendEvent("iterationStart", { iteration: iter, action: action.name });

        try {
          // Set current iteration for logging
          vu.currentIteration = iter;
          // action.fn is already the function (from entries)
          await action.fn();
          sendEvent("iterationEnd", { iteration: iter, action: action.name, status: "passed" });
        } catch (error) {
          vu.log("error", `Iteration ${iter} ${action.name} failed: ${error.message}`);
          sendEvent("iterationEnd", { iteration: iter, action: action.name, status: "failed", error: error.message });
          globalError = error;
          if (!vu.runOptions.continueOnError) break;
        }

        // Delay between iterations
        if (iter < action.iterations && vu.runOptions.iterationDelayMs > 0) {
          await new Promise(r => setTimeout(r, vu.runOptions.iterationDelayMs));
        }
      }
      if (globalError && !vu.runOptions.continueOnError) break;
    }

    // Send done BEFORE cleanup so parent gets it even if close hangs
    sendEvent("done", { runId, status: globalError ? "failed" : "passed", params: Object.fromEntries(vu.params) });

    // Cleanup (fire-and-forget with timeout)
    vu.http.close().catch((err) => {
      sendEvent("log", { level: "debug", msg: `[runner] http.close warning: ${err.message}` });
    });
    // Give time for done event to flush
    await new Promise(r => setTimeout(r, 100));
  } catch (error) {
    sendEvent("error", { message: `Runner fatal error: ${error.message}` });
    process.exit(1);
  }
}

// Handle messages from parent
process.on("message", (msg) => {
  if (msg?.type === "start") {
    run(msg.payload).catch((error) => {
      sendEvent("error", { message: `Runner fatal error: ${error.message}` });
      process.exit(1);
    });
  } else if (msg?.type === "stop") {
    // Keluar setelah event terkirim supaya parent tahu ini stop yang disengaja
    sendEvent("stopped", { reason: "Received stop signal" }, () => process.exit(0));
  }
});

// Handle uncaught errors
process.on("unhandledRejection", (reason) => {
  sendEvent("error", { message: `Unhandled rejection: ${reason}` });
});

process.on("uncaughtException", (error) => {
  sendEvent("error", { message: `Uncaught exception: ${error.message}` });
  process.exit(1);
});

// Notify parent ready
sendEvent("ready", {});